"""Freeze dependency closures from a verified environment for this exact platform."""
from importlib import metadata
import argparse
import json
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

BASE = Path(__file__).resolve().parents[1]


def roots(path):
    result = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("-r "):
            result.extend(roots(path.parent / line[3:]))
        else:
            result.append(Requirement(line))
    return result


def closure(requirements):
    pending = list(requirements)
    seen, result = set(), {}
    while pending:
        req = pending.pop()
        name = canonicalize_name(req.name)
        key = name, frozenset(req.extras)
        if key in seen:
            continue
        seen.add(key)
        distribution = metadata.distribution(req.name)
        if distribution.version not in req.specifier:
            raise ValueError(f"Installed version violates {req}")
        result[name] = distribution.version
        for raw in distribution.requires or []:
            dependency = Requirement(raw)
            if dependency.marker is None or any(dependency.marker.evaluate({"extra": extra})
                                                  for extra in ["", *req.extras]):
                pending.append(dependency)
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--profiles', nargs='+', choices=['core','models','indexing','ingestion'], default=['core','models','indexing'])
    args = parser.parse_args()
    header = "# Verified Windows x64 / CPython 3.12. Generated by scripts/lock_environment.py.\n"
    profiles = {}
    for profile in args.profiles:
        versions = closure(roots(BASE / f"requirements/{profile}.in"))
        profiles[profile] = versions
        text = header + "".join(f"{name}=={version}\n" for name, version in sorted(versions.items()))
        (BASE / f"requirements/{profile}.lock").write_text(text, encoding="utf-8")
    (BASE / "requirements.txt").write_text(
        "# Full inference runtime, Windows x64 / Python 3.12.\n-r requirements/models.lock\n", encoding="utf-8")
    (BASE / "requirements-dev.txt").write_text(
        "# unittest is bundled with Python; same verified runtime.\n-r requirements/models.lock\n", encoding="utf-8")
    print(json.dumps({name: len(versions) for name, versions in profiles.items()}))


if __name__ == "__main__":
    main()
